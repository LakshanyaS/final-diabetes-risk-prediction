/// predict_screen.dart
/// Sends patient data to the Flask API and shows results + SHAP contributions.
library;

import 'package:flutter/material.dart';
import 'package:google_fonts/google_fonts.dart';
import 'package:pdf/pdf.dart';
import 'package:pdf/widgets.dart' as pw;
import 'package:printing/printing.dart';

import '../services/api_service.dart';
import '../utils/theme.dart';
import '../widgets/app_card.dart';

class PredictScreen extends StatefulWidget {
  const PredictScreen({super.key});
  @override
  State<PredictScreen> createState() => _PredictScreenState();
}

class _PredictScreenState extends State<PredictScreen> {
  // ── Input state ──────────────────────────────────────────────────────────
  int _pregnancies = 1;
  double _glucose = 110;
  double _bp = 72;
  double _skin = 20;
  double _insulin = 79;
  double _bmi = 28.0;
  double _dpf = 0.47;
  int _age = 33;

  // ── Result state ─────────────────────────────────────────────────────────
  bool _loading = false;
  String? _error;
  Map<String, dynamic>? _result;

  // ── API call ─────────────────────────────────────────────────────────────
  Future<void> _predict() async {
    setState(() {
      _loading = true;
      _error = null;
      _result = null;
    });
    try {
      final res = await ApiService.predict(
        pregnancies: _pregnancies.toDouble(),
        glucose: _glucose,
        bloodPressure: _bp,
        skinThickness: _skin,
        insulin: _insulin,
        bmi: _bmi,
        dpf: _dpf,
        age: _age.toDouble(),
      );
      setState(() {
        _result = res;
      });
    } catch (e) {
      setState(() {
        _error = e.toString().replaceFirst('Exception: ', '');
      });
    } finally {
      setState(() {
        _loading = false;
      });
    }
  }

  // ── PDF export ────────────────────────────────────────────────────────────
  Future<void> _exportPdf() async {
    if (_result == null) return;
    final doc = pw.Document();
    final r = _result!;

    doc.addPage(pw.Page(
      pageFormat: PdfPageFormat.a4,
      margin: const pw.EdgeInsets.all(36),
      build: (ctx) => pw.Column(
        crossAxisAlignment: pw.CrossAxisAlignment.start,
        children: [
          pw.Text('Diabetes Risk Report',
              style:
                  pw.TextStyle(fontSize: 22, fontWeight: pw.FontWeight.bold)),
          pw.SizedBox(height: 4),
          pw.Text('Generated by Diabetes Risk AI (Flask + ML backend)',
              style: const pw.TextStyle(fontSize: 10)),
          pw.Divider(height: 24),
          pw.Text(
              'Result: ${r['pred_label']}  —  ${r['risk_level']} Risk  (${r['risk_pct'].toStringAsFixed(1)}%)',
              style:
                  pw.TextStyle(fontSize: 14, fontWeight: pw.FontWeight.bold)),
          pw.SizedBox(height: 16),
          pw.Text('Patient Inputs',
              style: pw.TextStyle(fontWeight: pw.FontWeight.bold)),
          pw.SizedBox(height: 6),
          pw.Text(
              'Pregnancies: $_pregnancies  |  Glucose: ${_glucose.toInt()}  |  '
              'BP: ${_bp.toInt()}  |  Skin: ${_skin.toInt()}\n'
              'Insulin: ${_insulin.toInt()}  |  BMI: ${_bmi.toStringAsFixed(1)}  |  '
              'DPF: ${_dpf.toStringAsFixed(3)}  |  Age: $_age'),
          pw.SizedBox(height: 16),
          pw.Text('Feature Contributions (SHAP)',
              style: pw.TextStyle(fontWeight: pw.FontWeight.bold)),
          pw.SizedBox(height: 6),
          if ((r['feature_contribs'] as Map?)?.isNotEmpty == true)
            ...((r['feature_contribs'] as Map<String, dynamic>).entries.toList()
                  ..sort((a, b) => (b.value as double)
                      .abs()
                      .compareTo((a.value as double).abs())))
                .map((e) => pw.Text(
                    '  ${e.key}: ${(e.value as double) >= 0 ? '+' : ''}${(e.value as double).toStringAsFixed(4)}'))
          else
            pw.Text('  Not available (install shap on the server)'),
          pw.SizedBox(height: 16),
          pw.Text('Health Suggestions',
              style: pw.TextStyle(fontWeight: pw.FontWeight.bold)),
          pw.SizedBox(height: 6),
          ...((r['suggestions'] as List?) ?? []).map(
              (s) => pw.Text('• $s', style: const pw.TextStyle(fontSize: 11))),
          pw.Spacer(),
          pw.Divider(),
          pw.Text(
            'Disclaimer: This is AI-based decision support and not a medical diagnosis. '
            'Always consult a qualified healthcare professional.',
            style: const pw.TextStyle(fontSize: 9),
          ),
        ],
      ),
    ));

    await Printing.sharePdf(
        bytes: await doc.save(), filename: 'diabetes_report.pdf');
  }

  // ── Build ─────────────────────────────────────────────────────────────────
  @override
  Widget build(BuildContext context) => SingleChildScrollView(
        padding: const EdgeInsets.fromLTRB(16, 16, 16, 100),
        child: Column(children: [
          _inputCard(),
          const SizedBox(height: 4),
          _predictButton(),
          if (_loading) ...[
            const SizedBox(height: 24),
            const CircularProgressIndicator(),
            const SizedBox(height: 10),
            Text('Contacting server...', style: AppText.body),
          ],
          if (_error != null) ...[
            const SizedBox(height: 16),
            _errorCard(),
          ],
          if (_result != null) ...[
            const SizedBox(height: 16),
            _resultCard(),
            _shapCard(),
            _suggestionsCard(),
            _pdfButton(),
          ],
        ]),
      );

  // ── Input card ───────────────────────────────────────────────────────────
  Widget _inputCard() => AppCard(
        child: Column(crossAxisAlignment: CrossAxisAlignment.start, children: [
          const CardTitle('Patient Data'),

          StepperField(
              label: 'Pregnancies',
              value: _pregnancies,
              min: 0,
              max: 20,
              onChanged: (v) => setState(() => _pregnancies = v)),
          const AppDivider(),

          SliderRow(
              label: 'Glucose',
              unit: 'mg/dL',
              displayValue: _glucose.toInt().toString(),
              value: _glucose,
              min: 0,
              max: 300,
              onChanged: (v) => setState(() => _glucose = v)),
          const AppDivider(),

          SliderRow(
              label: 'Blood Pressure',
              unit: 'mmHg',
              displayValue: _bp.toInt().toString(),
              value: _bp,
              min: 0,
              max: 150,
              onChanged: (v) => setState(() => _bp = v)),
          const AppDivider(),

          SliderRow(
              label: 'Skin Thickness',
              unit: 'mm',
              displayValue: _skin.toInt().toString(),
              value: _skin,
              min: 0,
              max: 100,
              onChanged: (v) => setState(() => _skin = v)),
          const AppDivider(),

          SliderRow(
              label: 'Insulin',
              unit: 'μU/mL',
              displayValue: _insulin.toInt().toString(),
              value: _insulin,
              min: 0,
              max: 900,
              onChanged: (v) => setState(() => _insulin = v)),
          const AppDivider(),

          SliderRow(
              label: 'BMI',
              unit: 'kg/m²',
              displayValue: _bmi.toStringAsFixed(1),
              value: _bmi,
              min: 10,
              max: 70,
              onChanged: (v) => setState(() => _bmi = v)),
          const AppDivider(),

          // DPF slider
          Column(crossAxisAlignment: CrossAxisAlignment.start, children: [
            Row(mainAxisAlignment: MainAxisAlignment.spaceBetween, children: [
              Text('Diabetes Pedigree Function', style: AppText.label),
              Text(_dpf.toStringAsFixed(3),
                  style: GoogleFonts.spaceMono(
                      fontSize: 18,
                      fontWeight: FontWeight.w700,
                      color: AppColors.accent)),
            ]),
            Slider(
                value: _dpf,
                min: 0.0,
                max: 2.5,
                divisions: 250,
                onChanged: (v) => setState(() => _dpf = v)),
            Row(mainAxisAlignment: MainAxisAlignment.spaceBetween, children: [
              Text('0.0',
                  style: GoogleFonts.spaceMono(
                      fontSize: 9, color: AppColors.textLight)),
              Text('2.5',
                  style: GoogleFonts.spaceMono(
                      fontSize: 9, color: AppColors.textLight)),
            ]),
          ]),
          const AppDivider(),

          StepperField(
              label: 'Age',
              unit: 'yrs',
              value: _age,
              min: 1,
              max: 120,
              onChanged: (v) => setState(() => _age = v)),
        ]),
      );

  // ── Predict button ────────────────────────────────────────────────────────
  Widget _predictButton() => SizedBox(
        width: double.infinity,
        child: ElevatedButton(
          onPressed: _loading ? null : _predict,
          child: const Text('Run Risk Analysis'),
        ),
      );

  // ── Error card ────────────────────────────────────────────────────────────
  Widget _errorCard() => AppCard(
        borderTopColor: AppColors.red,
        child: Column(crossAxisAlignment: CrossAxisAlignment.start, children: [
          const CardTitle('Connection Error'),
          Text(
              'Could not reach the Flask server.\n\n$_error\n\n'
              'Make sure the API is running:\n  python api/app.py\n\n'
              'Android emulator: base URL should be http://10.0.2.2:5000\n'
              'Real device: use your PC\'s LAN IP in api_service.dart',
              style: AppText.body),
        ]),
      );

  // ── Result card ───────────────────────────────────────────────────────────
  Widget _resultCard() {
    final r = _result!;
    final level = r['risk_level'] as String;
    final pct = (r['risk_pct'] as num).toDouble();
    final label = r['pred_label'] as String;
    final primary = AppColors.riskPrimary(level);
    final lightBg = AppColors.riskLight(level);
    final textColor = AppColors.riskText(level);

    return AppCard(
      borderTopColor: primary,
      child: Column(children: [
        const CardTitle('Prediction Result'),
        Container(
          width: double.infinity,
          padding: const EdgeInsets.symmetric(vertical: 24),
          decoration: BoxDecoration(
            color: lightBg,
            borderRadius: BorderRadius.circular(14),
          ),
          child: Column(children: [
            Text(label,
                style: GoogleFonts.plusJakartaSans(
                    fontSize: 22,
                    fontWeight: FontWeight.w800,
                    color: textColor)),
            const SizedBox(height: 6),
            Text('${pct.toStringAsFixed(1)}%',
                style: GoogleFonts.spaceMono(
                    fontSize: 52,
                    fontWeight: FontWeight.w700,
                    color: primary,
                    height: 1.0)),
            const SizedBox(height: 4),
            Text('$level Risk',
                style: GoogleFonts.plusJakartaSans(
                    fontSize: 14,
                    fontWeight: FontWeight.w700,
                    color: textColor)),
          ]),
        ),
        const SizedBox(height: 14),
        // Server badge
        Row(mainAxisAlignment: MainAxisAlignment.center, children: [
          Container(
            padding: const EdgeInsets.symmetric(horizontal: 10, vertical: 4),
            decoration: BoxDecoration(
              color: AppColors.accentBg,
              borderRadius: BorderRadius.circular(99),
            ),
            child: Text('Powered by Flask + ML backend',
                style: GoogleFonts.plusJakartaSans(
                    fontSize: 10,
                    fontWeight: FontWeight.w700,
                    color: AppColors.accent)),
          ),
        ]),
      ]),
    );
  }

  // ── SHAP contribution card ────────────────────────────────────────────────
  Widget _shapCard() {
    final contribs =
        (_result!['feature_contribs'] as Map<String, dynamic>?) ?? {};
    if (contribs.isEmpty) {
      return AppCard(
        child: Column(crossAxisAlignment: CrossAxisAlignment.start, children: [
          const CardTitle('Feature Contributions (SHAP)'),
          Text('Not available — install shap on the server and retrain.',
              style: AppText.body),
        ]),
      );
    }

    final sorted = contribs.entries.toList()
      ..sort((a, b) =>
          (b.value as double).abs().compareTo((a.value as double).abs()));
    final maxAbs = sorted
        .map((e) => (e.value as double).abs())
        .reduce((a, b) => a > b ? a : b);

    return AppCard(
      child: Column(crossAxisAlignment: CrossAxisAlignment.start, children: [
        const CardTitle('Feature Contributions (SHAP)'),
        Text(
            'How much each feature pushed this prediction towards Diabetes (+) or away from it (−).',
            style: AppText.body),
        const SizedBox(height: 14),
        ...sorted.map((e) {
          final val = (e.value as double);
          final pct = (val.abs() / maxAbs).clamp(0.0, 1.0);
          final color = val >= 0 ? AppColors.red : AppColors.green;
          return Padding(
            padding: const EdgeInsets.only(bottom: 12),
            child:
                Column(crossAxisAlignment: CrossAxisAlignment.start, children: [
              Row(mainAxisAlignment: MainAxisAlignment.spaceBetween, children: [
                Text(e.key, style: AppText.label),
                Text('${val >= 0 ? '+' : ''}${val.toStringAsFixed(4)}',
                    style: GoogleFonts.spaceMono(
                        fontSize: 11,
                        fontWeight: FontWeight.w700,
                        color: color)),
              ]),
              const SizedBox(height: 5),
              ClipRRect(
                borderRadius: BorderRadius.circular(99),
                child: LinearProgressIndicator(
                  value: pct,
                  minHeight: 8,
                  backgroundColor: AppColors.border,
                  valueColor: AlwaysStoppedAnimation(color),
                ),
              ),
            ]),
          );
        }),
        const SizedBox(height: 4),
        Text(
            'Red bars = pushed prediction toward Diabetes\nGreen bars = pushed away from Diabetes',
            style: GoogleFonts.plusJakartaSans(
                fontSize: 10, color: AppColors.textLight, height: 1.5)),
      ]),
    );
  }

  // ── Suggestions card ──────────────────────────────────────────────────────
  Widget _suggestionsCard() {
    final suggestions =
        ((_result!['suggestions'] as List?) ?? []).cast<String>();
    return AppCard(
      child: Column(crossAxisAlignment: CrossAxisAlignment.start, children: [
        const CardTitle('Health Suggestions'),
        ...suggestions.map((s) => Padding(
              padding: const EdgeInsets.only(bottom: 10),
              child:
                  Row(crossAxisAlignment: CrossAxisAlignment.start, children: [
                Text('•  ',
                    style: GoogleFonts.plusJakartaSans(
                        fontSize: 14,
                        color: AppColors.accent,
                        fontWeight: FontWeight.w700)),
                Expanded(child: Text(s, style: AppText.body)),
              ]),
            )),
        const SizedBox(height: 6),
        Text('Disclaimer: AI decision support only — not a medical diagnosis.',
            style: GoogleFonts.plusJakartaSans(
                fontSize: 10,
                color: AppColors.textLight,
                fontStyle: FontStyle.italic)),
      ]),
    );
  }

  // ── PDF export button ─────────────────────────────────────────────────────
  Widget _pdfButton() => Padding(
        padding: const EdgeInsets.only(top: 4),
        child: SizedBox(
          width: double.infinity,
          child: OutlinedButton(
            onPressed: _exportPdf,
            child: const Text('Export PDF Report'),
          ),
        ),
      );
}
